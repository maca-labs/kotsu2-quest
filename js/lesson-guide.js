function currentOperation(state,quest,provided){
 const live=state?.activeQuestKey?activeStep(state):null;
 if(live?.questId===quest.id)return live;
 const records=Object.values(state?.questStates??{}).filter(r=>r.questId===quest.id);
 const pending=records.find(r=>!r.completed);
 if(pending)return stepById[quest.stepIds[pending.index]]??null;
 if(records.some(r=>r.completed))return null;
 if(provided?.questId===quest.id)return provided;
 return stepById[quest.stepIds?.[0]]??null;
}

